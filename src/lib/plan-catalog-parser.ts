export interface CatalogPlan {
  name: string;
  monthly: number;
  deployedApps: number;
  /** Open pull requests that may hold a preview environment at once. */
  previewEnvironments: number;
  developerApps: number;
  concurrentInstances: number;
  ramMb: number;
  includedGbHours: number;
  /** Outbound traffic included per app each month, in GiB. */
  appEgressGib: number;
  appLayerMb: number;
  idleTimeout: string;
  maxRequestTimeout: string;
}

const HEADER =
  '| Plan | Monthly | Deployed apps | PR preview environments | Developer apps | Concurrent instances | RAM / app | Included GB-RAM-hours | App egress / month | App layer | Idle timeout | Max request timeout |';

const CELL_PATTERNS = [
  /^\*\*([A-Za-z]+)\*\*$/,
  /^\$(\d+(?:\.\d+)?)$/,
  /^(\d+)$/,
  /^(\d+)$/,
  /^(\d+)$/,
  /^(\d+)$/,
  /^(\d+) MB$/,
  /^(\d+)$/,
  /^([\d,]+) GiB$/,
  /^(\d+) MB$/,
  /^(\d+[smh])$/,
  /^(\d+[smh])$/,
];

/** The upstream Markdown is generated by make pricing-md from API limits.go.
 * Reject format changes during build rather than publishing guessed prices.
 *
 * Only the "At a glance" table is read: the generated page also carries
 * developer-environment, realtime and object-storage tables whose rows use the same bold
 * plan-name cells, so rows are taken from directly under the known header
 * rather than from anywhere in the document. */
export function parsePlanCatalog(source: string): {
  currency: 'USD';
  overagePerGbHour: number;
  plans: CatalogPlan[];
} {
  const lines = source.split('\n').map((line) => line.trimEnd());
  const headerIndex = lines.indexOf(HEADER);
  if (!source.includes('<!-- GENERATED') || headerIndex === -1) {
    throw new Error('Unrecognised generated plan catalog');
  }
  const rate = /billed at \$(\d+(?:\.\d+)?) per GB-RAM-hour/.exec(source);
  if (!rate) throw new Error('Missing USD overage rate');
  if (!/^\|(?:-+:?\|)+$/.test(lines[headerIndex + 1] ?? '')) {
    throw new Error('Missing plan table separator row');
  }
  const rows: string[] = [];
  for (const line of lines.slice(headerIndex + 2)) {
    if (!line.startsWith('|')) break;
    rows.push(line);
  }
  const plans = rows.map((line): CatalogPlan => {
    const cells = line
      .split('|')
      .slice(1, -1)
      .map((cell) => cell.trim());
    const values = CELL_PATTERNS.map((pattern, index) => pattern.exec(cells[index] ?? '')?.[1]);
    if (cells.length !== CELL_PATTERNS.length || values.some((value) => value === undefined)) {
      throw new Error(`Invalid plan row: ${line}`);
    }
    return {
      name: values[0]!,
      monthly: Number(values[1]),
      deployedApps: Number(values[2]),
      previewEnvironments: Number(values[3]),
      developerApps: Number(values[4]),
      concurrentInstances: Number(values[5]),
      ramMb: Number(values[6]),
      includedGbHours: Number(values[7]),
      appEgressGib: Number(values[8]!.replaceAll(',', '')),
      appLayerMb: Number(values[9]),
      idleTimeout: values[10]!,
      maxRequestTimeout: values[11]!,
    };
  });
  if (plans.map((plan) => plan.name).join(',') !== 'Free,Hobby,Pro,Scale') {
    throw new Error('Unexpected self-service plan set');
  }
  return { currency: 'USD', overagePerGbHour: Number(rate[1]), plans };
}
